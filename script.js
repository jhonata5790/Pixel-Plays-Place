/* =========================================
   FILTRAR JOGOS
========================================= */

function obterJogosFiltrados(
  filtro
) {

  if (
    filtro === "todos"
  ) {

    return jogos;

  }


  return jogos.filter(
    jogo =>
      jogo.categoria === filtro
  );

}



/* =========================================
   RENDERIZAR
========================================= */

function renderizarJogos(
  filtro = "todos"
) {

  if (!gamesGrid) {
    return;
  }


  gamesGrid.innerHTML = "";


  const jogosFiltrados =
    obterJogosFiltrados(
      filtro
    );



  if (
    jogosFiltrados.length === 0
  ) {

    if (emptyState) {

      emptyState.style.display =
        "block";

    }

    return;

  }



  if (emptyState) {

    emptyState.style.display =
      "none";

  }



  jogosFiltrados.forEach(
    jogo => {

      const card =
        criarCard(jogo);


      gamesGrid.appendChild(
        card
      );

    }
  );

}



/* =========================================
   BOTÕES DOS FILTROS
========================================= */

function iniciarFiltros() {

  filters.forEach(
    botao => {

      botao.addEventListener(
        "click",
        () => {

          filters.forEach(
            item => {

              item.classList.remove(
                "active"
              );

            }
          );


          botao.classList.add(
            "active"
          );


          const filtro =
            botao.dataset.filter;


          renderizarJogos(
            filtro
          );

        }
      );

    }
  );

}



/* =========================================
   ESTATÍSTICAS
========================================= */

function atualizarEstatisticas() {

  const totalJogos =
    jogos.length;


  const totalParcerias =
    jogos.filter(
      jogo =>
        jogo.categoria ===
        "marketing"
    ).length;


  const plataformas =
    new Set(
      jogos.map(
        jogo =>
          jogo.plataforma
      )
    );



  const totalJogosElement =
    document.getElementById(
      "totalJogos"
    );


  const totalParceriasElement =
    document.getElementById(
      "totalParcerias"
    );


  const totalPlataformasElement =
    document.getElementById(
      "totalPlataformas"
    );



  if (totalJogosElement) {

    totalJogosElement.textContent =
      totalJogos;

  }


  if (totalParceriasElement) {

    totalParceriasElement.textContent =
      totalParcerias;

  }


  if (totalPlataformasElement) {

    totalPlataformasElement.textContent =
      plataformas.size;

  }

}



/* =========================================
   ANO AUTOMÁTICO
========================================= */

function atualizarAno() {

  const currentYear =
    document.getElementById(
      "currentYear"
    );


  if (!currentYear) {
    return;
  }


  currentYear.textContent =
    new Date().getFullYear();

}



/* =========================================
   SCROLL SUAVE DOS LINKS INTERNOS
========================================= */

function iniciarScrollInterno() {

  const linksInternos =
    document.querySelectorAll(
      'a[href^="#"]'
    );


  linksInternos.forEach(
    link => {

      link.addEventListener(
        "click",
        event => {

          const href =
            link.getAttribute(
              "href"
            );


          if (
            !href ||
            href === "#"
          ) {
            return;
          }


          const destino =
            document.querySelector(
              href
            );


          if (!destino) {
            return;
          }


          event.preventDefault();


          destino.scrollIntoView({
            behavior: "smooth",
            block: "start"
          });

        }
      );

    }
  );

}



/* =========================================
   HEADER AO ROLAR
========================================= */

function iniciarHeaderScroll() {

  const header =
    document.querySelector(
      ".header"
    );


  if (!header) {
    return;
  }


  function atualizarHeader() {

    if (
      window.scrollY > 30
    ) {

      header.classList.add(
        "scrolled"
      );

    } else {

      header.classList.remove(
        "scrolled"
      );

    }

  }


  window.addEventListener(
    "scroll",
    atualizarHeader,
    {
      passive: true
    }
  );


  atualizarHeader();

}



/* =========================================
   ANIMAÇÃO SIMPLES DOS CARDS
========================================= */

function iniciarAnimacaoCards() {

  if (
    !("IntersectionObserver" in window)
  ) {
    return;
  }


  const observer =
    new IntersectionObserver(

      entries => {

        entries.forEach(
          entry => {

            if (
              !entry.isIntersecting
            ) {
              return;
            }


            entry.target.classList.add(
              "card-visible"
            );


            observer.unobserve(
              entry.target
            );

          }
        );

      },

      {
        threshold: 0.1
      }

    );



  const cards =
    document.querySelectorAll(
      ".game-card"
    );


  cards.forEach(
    card =>
      observer.observe(card)
  );

}



/* =========================================
   OBSERVAR NOVOS CARDS APÓS FILTROS
========================================= */

function observarCardsAtuais() {

  if (
    !("IntersectionObserver" in window)
  ) {
    return;
  }


  const cards =
    document.querySelectorAll(
      ".game-card"
    );


  cards.forEach(
    card => {

      requestAnimationFrame(
        () => {

          card.classList.add(
            "card-visible"
          );

        }
      );

    }
  );

}



/* =========================================
   RENDER COM ANIMAÇÃO
========================================= */

function renderizarJogosComAnimacao(
  filtro = "todos"
) {

  renderizarJogos(
    filtro
  );


  observarCardsAtuais();

}



/* =========================================
   FILTROS COM ANIMAÇÃO
========================================= */

function iniciarFiltrosComAnimacao() {

  filters.forEach(
    botao => {

      botao.addEventListener(
        "click",
        () => {

          filters.forEach(
            item =>
              item.classList.remove(
                "active"
              )
          );


          botao.classList.add(
            "active"
          );


          renderizarJogosComAnimacao(
            botao.dataset.filter
          );

        }
      );

    }
  );

}



/* =========================================
   INICIAR SITE
========================================= */

function iniciarSite() {

  renderizarJogos();

  atualizarEstatisticas();

  atualizarAno();

  iniciarScrollInterno();

  iniciarHeaderScroll();

  iniciarFiltrosComAnimacao();

  iniciarAnimacaoCards();

}



/* =========================================
   DOM READY
========================================= */

document.addEventListener(
  "DOMContentLoaded",
  iniciarSite
);